#!/usr/bin/env python3
"""Generate Ansible checksum variables and a human-readable SHA256SUMS manifest."""
from __future__ import annotations
import hashlib
import sys
from pathlib import Path

role = Path(sys.argv[1]).resolve()
architectures = ("amd64", "arm64")
names = ("minio", "mc")
checksums: dict[str, dict[str, str]] = {}
lines: list[str] = []
for arch in architectures:
    checksums[arch] = {}
    for name in names:
        path = role / "files" / "bin" / arch / name
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        checksums[arch][name] = digest
        lines.append(f"{digest}  files/bin/{arch}/{name}")

manifest = ["---", "# GENERATED by build/build.sh. Do not hand-edit checksums.", "_anro_minio_binary_checksums:"]
for arch in architectures:
    manifest.append(f"  {arch}:")
    for name in names:
        manifest.append(f"    {name}: '{checksums[arch][name]}'")
(role / "vars" / "binary_checksums.yml").write_text("\n".join(manifest) + "\n")
(role / "SHA256SUMS").write_text("\n".join(lines) + "\n")
